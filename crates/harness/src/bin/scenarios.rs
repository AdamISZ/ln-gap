//! Run every scenario against regtest, print the narrative, and write
//! design-notes/SCENARIOS.md. With `--keep`, each scenario's regtest datadir is left
//! at ./regtest-data/<scenario>/ together with its report (SCENARIO.md); the
//! directory is wiped at the start of the next run of that scenario, after
//! stopping any node tools/explorer.sh still has on it.
//! Usage: cargo run -p lngap-harness --bin scenarios [-- --keep] [filter]

use std::fmt::Write as _;
use std::path::PathBuf;

/// The kept datadir for scenario `id`.
fn kept_datadir(id: &str) -> PathBuf {
    PathBuf::from("regtest-data").join(id)
}

fn main() -> anyhow::Result<()> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    if args.iter().any(|a| a == "--keep") {
        std::env::set_var("LNGAP_KEEP_DATADIR", "1");
    }
    let filter: Option<&String> = args.iter().find(|a| !a.starts_with("--"));
    lngap_harness::init_log();
    let mut out = String::new();
    writeln!(out, "# Scenarios\n\nGenerated by `cargo run -p lngap-harness --bin scenarios` against a throwaway regtest\nchain (txids are from that run and change every run). Heights are absolute regtest\nheights; the channel is funded at height ~204 in every scenario.\n\nThe PS* sections run the PoS-venue graph (pos-factchain branch, plan step 7): the\ncontract output is funded directly and the graph played by hand — the force-close\ncommitment (~240 vB, unchanged by the venue swap) is excluded from their\ntransaction tables, and their balances are the payout outputs' on-chain totals.\n")?;
    let mut failures = Vec::new();
    for sc in lngap_harness::scenarios::all() {
        if let Some(f) = filter {
            if !sc.id.eq_ignore_ascii_case(f) {
                continue;
            }
        }
        eprintln!("===== {} — {}", sc.id, sc.title);
        std::env::set_var("LNGAP_RUN_LABEL", sc.id);
        match (sc.run)() {
            Ok(r) => {
                let mut section = String::new();
                writeln!(section, "## {} — {}\n\n**Expected:** {}\n\n**Final balances (Alice's/user's channel; on-chain if closed, else off-chain):** user {} sat, hub {} sat\n", r.id, r.title, r.expected, r.balances[0].to_sat(), r.balances[1].to_sat())?;
                writeln!(section, "| block | tx | broadcast by | txid |\n|---|---|---|---|")?;
                for (h, role, txid, by) in &r.txs {
                    writeln!(section, "| {h} | `{role}` | {by} | `{txid}` |")?;
                }
                writeln!(section, "\n<details><summary>narrative</summary>\n\n```\n{}\n```\n</details>\n", r.narrative)?;
                out.push_str(&section);
                // with --keep, the report travels with the chain it describes
                if std::env::var("LNGAP_KEEP_DATADIR").is_ok() {
                    let d = kept_datadir(sc.id);
                    if d.exists() {
                        std::fs::write(d.join("SCENARIO.md"), &section)?;
                        eprintln!("kept {} with its report in SCENARIO.md", d.display());
                    }
                }
            }
            Err(e) => {
                writeln!(out, "## {} — {}\n\n**FAILED:** {e:#}\n", sc.id, sc.title)?;
                failures.push(sc.id);
            }
        }
    }
    if filter.is_none() {
        let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../design-notes/SCENARIOS.md");
        std::fs::write(&path, out)?;
        eprintln!("wrote {}", path.display());
    } else {
        eprintln!("(single scenario: design-notes/SCENARIOS.md left untouched; the report is in regtest-data/<id>/SCENARIO.md with --keep)");
    }
    if !failures.is_empty() {
        anyhow::bail!("failed scenarios: {failures:?}");
    }
    Ok(())
}
