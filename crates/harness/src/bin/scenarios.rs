//! Run every scenario against regtest, print the narrative, and write
//! docs/SCENARIOS.md. With `--keep`, each scenario's regtest datadir is left
//! under ./regtest-data/<scenario>-<millis>-<n> (bitcoind is stopped; start
//! it again on that datadir to inspect the chain).
//! Usage: cargo run -p lngap-harness --bin scenarios [-- --keep] [filter]

use std::fmt::Write as _;
use std::path::PathBuf;

fn main() -> anyhow::Result<()> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    if args.iter().any(|a| a == "--keep") {
        std::env::set_var("LNGAP_KEEP_DATADIR", "1");
    }
    let filter: Option<&String> = args.iter().find(|a| !a.starts_with("--"));
    lngap_harness::init_log();
    let mut out = String::new();
    writeln!(out, "# Scenarios\n\nGenerated by `cargo run -p lngap-harness --bin scenarios` against a throwaway regtest\nchain (txids are from that run and change every run). Heights are absolute regtest\nheights; the channel is funded at height ~204 in every scenario.\n")?;
    let mut failures = Vec::new();
    for sc in lngap_harness::scenarios::all() {
        if let Some(f) = filter {
            if !sc.id.eq_ignore_ascii_case(f) {
                continue;
            }
        }
        eprintln!("===== {} — {}", sc.id, sc.title);
        std::env::set_var("LNGAP_RUN_LABEL", sc.id);
        match (sc.run)() {
            Ok(r) => {
                writeln!(out, "## {} — {}\n\n**Expected:** {}\n\n**Final balances (Alice's/user's channel; on-chain if closed, else off-chain):** user {} sat, hub {} sat\n", r.id, r.title, r.expected, r.balances[0].to_sat(), r.balances[1].to_sat())?;
                writeln!(out, "| block | tx | broadcast by | txid |\n|---|---|---|---|")?;
                for (h, role, txid, by) in &r.txs {
                    writeln!(out, "| {h} | `{role}` | {by} | `{txid}` |")?;
                }
                writeln!(out, "\n<details><summary>narrative</summary>\n\n```\n{}\n```\n</details>\n", r.narrative)?;
            }
            Err(e) => {
                writeln!(out, "## {} — {}\n\n**FAILED:** {e:#}\n", sc.id, sc.title)?;
                failures.push(sc.id);
            }
        }
    }
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../docs/SCENARIOS.md");
    std::fs::write(&path, out)?;
    eprintln!("wrote {}", path.display());
    if !failures.is_empty() {
        anyhow::bail!("failed scenarios: {failures:?}");
    }
    Ok(())
}
