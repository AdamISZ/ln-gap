//! Run every scenario against regtest, print the narrative, and write
//! docs/SCENARIOS.md. With `--keep`, each scenario's regtest datadir is left
//! under ./regtest-data/<scenario>-<millis>-<n> (bitcoind is stopped; start
//! it again on that datadir to inspect the chain).
//! Usage: cargo run -p lngap-harness --bin scenarios [-- --keep] [filter]

use std::fmt::Write as _;
use std::path::PathBuf;

/// Datadirs under ./regtest-data created for scenario `id` (newest run's; a
/// two-channel scenario has one node, others too, but keep it general).
fn kept_datadirs(id: &str) -> Vec<PathBuf> {
    let mut v: Vec<PathBuf> = std::fs::read_dir("regtest-data")
        .map(|rd| rd.flatten().map(|e| e.path()).filter(|p| p.file_name().and_then(|n| n.to_str()).is_some_and(|n| n.starts_with(&format!("{id}-")))).collect())
        .unwrap_or_default();
    v.sort();
    v
}

fn main() -> anyhow::Result<()> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    if args.iter().any(|a| a == "--keep") {
        std::env::set_var("LNGAP_KEEP_DATADIR", "1");
    }
    let filter: Option<&String> = args.iter().find(|a| !a.starts_with("--"));
    lngap_harness::init_log();
    let mut out = String::new();
    writeln!(out, "# Scenarios\n\nGenerated by `cargo run -p lngap-harness --bin scenarios` against a throwaway regtest\nchain (txids are from that run and change every run). Heights are absolute regtest\nheights; the channel is funded at height ~204 in every scenario.\n")?;
    let mut failures = Vec::new();
    for sc in lngap_harness::scenarios::all() {
        if let Some(f) = filter {
            if !sc.id.eq_ignore_ascii_case(f) {
                continue;
            }
        }
        eprintln!("===== {} — {}", sc.id, sc.title);
        std::env::set_var("LNGAP_RUN_LABEL", sc.id);
        let before = kept_datadirs(sc.id);
        match (sc.run)() {
            Ok(r) => {
                let mut section = String::new();
                writeln!(section, "## {} — {}\n\n**Expected:** {}\n\n**Final balances (Alice's/user's channel; on-chain if closed, else off-chain):** user {} sat, hub {} sat\n", r.id, r.title, r.expected, r.balances[0].to_sat(), r.balances[1].to_sat())?;
                writeln!(section, "| block | tx | broadcast by | txid |\n|---|---|---|---|")?;
                for (h, role, txid, by) in &r.txs {
                    writeln!(section, "| {h} | `{role}` | {by} | `{txid}` |")?;
                }
                writeln!(section, "\n<details><summary>narrative</summary>\n\n```\n{}\n```\n</details>\n", r.narrative)?;
                out.push_str(&section);
                // with --keep, the report travels with the chain it describes
                if std::env::var("LNGAP_KEEP_DATADIR").is_ok() {
                    // only the datadir(s) this run created, never an earlier kept chain's
                    for d in kept_datadirs(sc.id).into_iter().filter(|d| !before.contains(d)) {
                        std::fs::write(d.join("SCENARIO.md"), &section)?;
                        eprintln!("kept {} with its report in SCENARIO.md", d.display());
                    }
                }
            }
            Err(e) => {
                writeln!(out, "## {} — {}\n\n**FAILED:** {e:#}\n", sc.id, sc.title)?;
                failures.push(sc.id);
            }
        }
    }
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../docs/SCENARIOS.md");
    std::fs::write(&path, out)?;
    eprintln!("wrote {}", path.display());
    if !failures.is_empty() {
        anyhow::bail!("failed scenarios: {failures:?}");
    }
    Ok(())
}
